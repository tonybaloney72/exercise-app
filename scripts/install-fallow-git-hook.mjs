#!/usr/bin/env node
/**
 * Wire .git/hooks/pre-commit -> scripts/fallow-pre-commit.sh
 * Skips quietly when not in a git repo (e.g. npm pack).
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const gitDir = join(root, ".git");
const hooksDir = join(gitDir, "hooks");
const hookPath = join(hooksDir, "pre-commit");
const scriptRel = "scripts/fallow-pre-commit.sh";

if (!existsSync(gitDir)) {
  process.exit(0);
}

const scriptPath = join(root, scriptRel);
if (!existsSync(scriptPath)) {
  console.warn("[fallow:hooks] Missing", scriptRel);
  process.exit(0);
}

mkdirSync(hooksDir, { recursive: true });

const wrapper = `#!/bin/sh
# Generated by scripts/install-fallow-git-hook.mjs — do not edit; change ${scriptRel} instead.
exec "$(git rev-parse --show-toplevel)/${scriptRel.replace(/\\/g, "/")}"
`;

writeFileSync(hookPath, wrapper, { mode: 0o755 });
try {
  chmodSync(scriptPath, 0o755);
} catch {
  // Windows: executable bit may be ignored
}

console.log("Installed .git/hooks/pre-commit ->", scriptRel);
